"""Generate and check the parameter-bound certificate artifacts."""

from __future__ import annotations

import hashlib
import json
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Any

LOGGER = logging.getLogger(__name__)

BENCHMARK = "cartpole-gym-v1"
WITNESS = Path("models/cartpole-gym-v1/relu-threshold-9")
GENERATED_LEAN = Path("proofs/lean/Proofs/Generated.lean")
BOUNDS_JSON = Path("proofs/bounds.json")
ACCEPTANCE_JSON = Path("proofs/acceptance.json")
ARCHITECTURES_JSON = Path("proofs/architectures.json")
CONTROL_SPEC = Path("src/minimal_nn_competition/benchmarks/common/control/spec.json")


class ProofError(RuntimeError):
    """Raised when a certificate cannot be generated or checked."""


@dataclass(frozen=True)
class Architecture:
    label: str
    input_size: int
    hidden_sizes: tuple[int, ...]
    output_size: int
    parameters: int


def parameter_count(input_size: int, hidden_sizes: tuple[int, ...], output_size: int) -> int:
    """Mirror the evaluator's parameter formula, including biases."""
    total = 0
    previous = input_size
    for width in (*hidden_sizes, output_size):
        total += previous * width + width
        previous = width
    return total


def architectural_floor(input_size: int, output_size: int) -> int:
    """Minimum of the linear and one-hidden-unit architectures."""
    return min((input_size + 1) * output_size, input_size + 1 + 2 * output_size)


def _read_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise ProofError(f"Could not read {path}: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise ProofError(f"Invalid JSON in {path}: {exc}") from exc


def load_architectures(root: Path) -> tuple[Architecture, ...]:
    raw = _read_json(root / ARCHITECTURES_JSON)
    if not isinstance(raw, list) or not raw:
        raise ProofError(f"{ARCHITECTURES_JSON} must be a non-empty list")
    architectures = []
    for item in raw:
        if not isinstance(item, dict):
            raise ProofError(f"{ARCHITECTURES_JSON} entries must be objects")
        try:
            architecture = Architecture(
                label=str(item["label"]),
                input_size=int(item["input_size"]),
                hidden_sizes=tuple(int(width) for width in item["hidden_sizes"]),
                output_size=int(item["output_size"]),
                parameters=int(item["parameters"]),
            )
        except (KeyError, TypeError, ValueError) as exc:
            raise ProofError(f"Invalid architecture entry {item!r}: {exc}") from exc
        computed = parameter_count(
            architecture.input_size, architecture.hidden_sizes, architecture.output_size
        )
        if computed != architecture.parameters:
            raise ProofError(
                f"{architecture.label}: declared {architecture.parameters} parameters, "
                f"formula gives {computed}"
            )
        architectures.append(architecture)
    return tuple(architectures)


def _lean_list(values: tuple[int, ...]) -> str:
    return "[" + ", ".join(str(value) for value in values) + "]"


def render_generated_lean(architectures: tuple[Architecture, ...]) -> str:
    lines = [
        "-- Generated by `python -m proofs generate-lean`; do not edit.",
        "import Proofs.Architecture",
        "",
        "namespace MinimalNN",
        "",
        "example : (Claim.mk 4 2 [1] 9).check = true := by decide",
        "",
    ]
    ordered = sorted(
        architectures,
        key=lambda item: (
            item.input_size,
            item.output_size,
            item.hidden_sizes,
            item.label,
        ),
    )
    for architecture in ordered:
        lines.append(
            f"-- {architecture.label}: input {architecture.input_size}, "
            f"hidden {_lean_list(architecture.hidden_sizes)}, "
            f"output {architecture.output_size}"
        )
        lines.append(
            f"example : parameterCount {architecture.input_size} {architecture.output_size} "
            f"{_lean_list(architecture.hidden_sizes)} = {architecture.parameters} := by decide"
        )
        lines.append("")
    floors = sorted({(item.input_size, item.output_size) for item in ordered})
    for input_size, output_size in floors:
        lines.append(
            f"example : architecturalFloor {input_size} {output_size} = "
            f"{architectural_floor(input_size, output_size)} := by decide"
        )
    lines.extend(["", "end MinimalNN"])
    return "\n".join(lines) + "\n"


def _sha256(path: Path) -> str:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError as exc:
        raise ProofError(f"Could not hash {path}: {exc}") from exc


def verify_acceptance(root: Path) -> dict[str, Any]:
    acceptance = _read_json(root / ACCEPTANCE_JSON)
    if acceptance.get("schema") != "mnnc.acceptance.v1":
        raise ProofError(f"{ACCEPTANCE_JSON} has an unexpected schema")
    if acceptance.get("benchmark") != BENCHMARK:
        raise ProofError(f"{ACCEPTANCE_JSON} must describe {BENCHMARK}")
    architecture = acceptance.get("architecture", {})
    if architecture.get("input_size") != 4 or architecture.get("output_size") != 2:
        raise ProofError(
            "CartPole acceptance dimensions changed; revalidate the theorem and update "
            f"{ACCEPTANCE_JSON}"
        )
    if architecture.get("min_hidden_width") != 1:
        raise ProofError(
            "CartPole hidden-width rule changed; revalidate the theorem and update "
            f"{ACCEPTANCE_JSON}"
        )
    pinned = acceptance.get("source_sha256")
    if not isinstance(pinned, dict) or not pinned:
        raise ProofError(f"{ACCEPTANCE_JSON} must pin source_sha256 entries")
    changed = []
    for relative, expected in sorted(pinned.items()):
        actual = _sha256(root / relative)
        if actual != expected:
            changed.append(relative)
    if changed:
        raise ProofError(
            "Acceptance sources changed: "
            + ", ".join(changed)
            + ". Revalidate the CartPole architectural theorem, then update "
            + f"{ACCEPTANCE_JSON}."
        )
    return acceptance


def _spec(root: Path) -> dict[str, Any]:
    spec_path = root / CONTROL_SPEC
    spec = _read_json(spec_path)
    task = spec.get("tasks", {}).get(BENCHMARK)
    if not isinstance(task, dict):
        raise ProofError(f"{CONTROL_SPEC} does not define {BENCHMARK}")
    if task.get("inputs") != 4 or task.get("outputs") != 2:
        raise ProofError(
            "CartPole dimensions changed; update proofs/lean/Proofs/CartPole.lean and "
            f"{ACCEPTANCE_JSON}"
        )
    return {
        "benchmark": BENCHMARK,
        "control_spec_version": spec.get("version"),
        "control_spec_sha256": _sha256(spec_path),
        "inputs": task["inputs"],
        "outputs": task["outputs"],
        "seeds": len(spec.get("seeds", [])),
        "horizon": task.get("horizon"),
        "threshold": task.get("threshold"),
    }


def evaluate_witness(root: Path) -> dict[str, Any]:
    try:
        from minimal_nn_competition.benchmarks.registry import create_benchmark
        from minimal_nn_competition.model.entry import (
            Submission,
            materialize_submission,
        )
        from minimal_nn_competition.model.entry import (
            parameter_count as state_dict_parameter_count,
        )
    except ImportError as exc:
        raise ProofError(
            "The witness evaluation needs the competition package and torch; "
            "run `uv sync --dev --locked` first."
        ) from exc

    submission_dir = root / WITNESS
    try:
        loaded = materialize_submission(Submission.from_directory(submission_dir))
    except (OSError, ValueError) as exc:
        raise ProofError(f"Could not load witness {WITNESS}: {exc}") from exc

    config = loaded.config
    if config.benchmark != BENCHMARK:
        raise ProofError(f"Witness benchmark is {config.benchmark!r}, expected {BENCHMARK!r}")
    if (config.input_size, config.output_size) != (4, 2):
        raise ProofError(f"Witness dimensions are {(config.input_size, config.output_size)}")
    if tuple(config.hidden_sizes) != (1,):
        raise ProofError(f"Witness hidden sizes are {config.hidden_sizes}, expected (1,)")
    if config.input_indices is not None:
        raise ProofError("Witness must not select input features")

    state_dict_count = state_dict_parameter_count(loaded.state_dict)
    if state_dict_count != 9:
        raise ProofError(f"Witness state dict has {state_dict_count} parameters, expected 9")
    formula_count = parameter_count(
        config.input_size, tuple(config.hidden_sizes), config.output_size
    )
    if formula_count != 9:
        raise ProofError(f"Witness formula count is {formula_count}, expected 9")

    try:
        score, passed, details = create_benchmark(BENCHMARK).evaluate(loaded)
    except (RuntimeError, ValueError) as exc:
        raise ProofError(f"Witness evaluation failed: {exc}") from exc

    successes = details.get("seed_success", [])
    if not passed or score != 1.0 or len(successes) != 100 or not all(successes):
        raise ProofError(
            f"Witness did not pass cleanly: score={score!r}, passed={passed!r}, "
            f"successes={len(successes)}"
        )

    return {
        "kind": "empirical_witness",
        "value": 9,
        "submission": str(WITNESS),
        "score": score,
        "passed": passed,
        "seeds": len(successes),
        "evaluation_sha256": details.get("evaluation_sha256"),
        "checkpoint_sha256": _sha256(submission_dir / "model.pt"),
        "config_sha256": _sha256(submission_dir / "config.json"),
    }


def build_bounds(root: Path) -> dict[str, Any]:
    verify_acceptance(root)
    spec = _spec(root)
    lower = architectural_floor(4, 2)
    if lower != 9:
        raise ProofError(f"CartPole architectural floor is {lower}, expected 9")
    witness = evaluate_witness(root)
    return {
        "schema": "mnnc.parameter-bounds.v1",
        "benchmark": BENCHMARK,
        "evidence": {
            "formal_theorem": {
                "kind": "formal_theorem",
                "value": 9,
                "statement": ("every accepted CartPole MLP architecture has at least 9 parameters"),
                "theorem": "MinimalNN.cartPole_architecturalMinimum",
                "file": "proofs/lean/Proofs/CartPole.lean",
            },
            "computation_certificate": {
                "kind": "computation_certificate",
                "file": str(GENERATED_LEAN),
                "checked_by": "lake build",
                "claims": [
                    "parameterCount 4 2 [1] = 9",
                    "architecturalFloor 4 2 = 9",
                ],
            },
            "empirical_witness": witness,
        },
        "conclusion": {
            "statement": "the minimum passing parameter count is 9",
            "value": 9,
            "status": "combined",
            "requires": ["formal_theorem", "empirical_witness"],
            "note": (
                "the architectural lower bound is Lean-verified; "
                "the 9-parameter upper bound is evaluator-verified"
            ),
        },
        "spec": spec,
        "acceptance": {
            "file": str(ACCEPTANCE_JSON),
            "sha256": _sha256(root / ACCEPTANCE_JSON),
        },
    }


def render_document(document: dict[str, Any]) -> str:
    return json.dumps(document, indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def _compare(label: str, expected: str, actual_path: Path) -> None:
    try:
        actual = actual_path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ProofError(f"Could not read {actual_path}: {exc}") from exc
    if actual != expected:
        raise ProofError(f"{label} is stale: regenerate it with `python -m proofs generate`")


def check_lean(root: Path) -> None:
    generated = render_generated_lean(load_architectures(root))
    _compare("Generated Lean certificate", generated, root / GENERATED_LEAN)
    LOGGER.info("generated Lean certificate: current")


def check(root: Path) -> None:
    document = build_bounds(root)
    _compare("bounds manifest", render_document(document), root / BOUNDS_JSON)
    check_lean(root)
    LOGGER.info("bounds manifest: current")
    LOGGER.info("CartPole: architectural lower bound 9, passing upper bound 9 (combined)")


def generate(root: Path) -> None:
    architectures = load_architectures(root)
    document = build_bounds(root)
    (root / GENERATED_LEAN).write_text(render_generated_lean(architectures), encoding="utf-8")
    (root / BOUNDS_JSON).write_text(render_document(document), encoding="utf-8")
    LOGGER.info("wrote %s and %s", GENERATED_LEAN, BOUNDS_JSON)


def generate_lean(root: Path) -> None:
    architectures = load_architectures(root)
    (root / GENERATED_LEAN).write_text(render_generated_lean(architectures), encoding="utf-8")
    LOGGER.info("wrote %s", GENERATED_LEAN)
